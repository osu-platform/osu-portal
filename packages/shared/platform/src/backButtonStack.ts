/**
 * Кто отвечает на нажатие кнопки «назад» в шапке хоста.
 *
 * Кнопка одна, а мест, откуда пользователь хочет вернуться, много: экран мероприятия,
 * поверх него шторка, поверх неё модалка. Поэтому обработчики складываются в стек, и
 * нажатие получает верхний — то, что пользователь видит последним. Открыта модалка —
 * «назад» закрывает модалку, следующее нажатие уводит с экрана. Без этого нажатие при
 * открытой шторке закрывало бы мини-приложение целиком: для мессенджера «назад» на первом
 * экране означает «выйти», а про наши оверлеи он ничего не знает.
 *
 * Видимость кнопки — производная от стека: пусто (лента, дашборд, любой корневой экран) —
 * кнопки нет, и «назад» работает штатно, то есть закрывает мини-приложение. Видимая
 * кнопка, которая ничего не делает, хуже отсутствующей.
 *
 * Подписка на хост ровно одна и живёт здесь. Дать каждому экрану подписываться самому
 * значило бы гонку из onClick/offClick при переходах и «призрачные» обработчики от
 * размонтированных экранов — ровно те дефекты, из-за которых кнопка потом уводит не туда
 * через раз.
 *
 * Здесь нет React намеренно: контракт нужен и хост-приложениям, и SDK модулей, а связывание
 * с деревом компонентов — дело `@portal/module-sdk`.
 */

import type { BackButtonAdapter } from "./adapters/base"

/** Нажатия, пришедшие подряд быстрее этого, считаются одним. Мессенджер может доставить
 * событие дважды, а палец на телефоне легко бьёт дважды по инерции; два «назад» подряд —
 * это прыжок через экран, после которого пользователь уже не понимает, где он. */
const REPEAT_GUARD_MS = 300

export interface BackButtonStack {
  /** Рисует ли хост кнопку на самом деле. По этому признаку экраны прячут свои. */
  isSupported(): boolean
  /** Занять кнопку. Возвращает снятие — вызывать при закрытии экрана или оверлея. */
  register(handler: () => void): () => void
  /** Отписаться от хоста и убрать кнопку. Вызывается при размонтировании приложения. */
  dispose(): void
}

export const createBackButtonStack = (
  adapter: BackButtonAdapter
): BackButtonStack => {
  // Спрашиваем адаптер каждый раз, а не запоминаем ответ при создании. Мост мессенджера
  // появляется в окне не по нашему расписанию: спросив однажды и рано, можно навсегда
  // запомнить «кнопки нет» — и дальше молча игнорировать все регистрации, то есть получить
  // ровно тот симптом, ради которого всё это писалось, только необъяснимый.
  const supported = () => adapter.isSupported()
  let handlers: Array<() => void> = []
  let lastFiredAt = 0
  let subscribed = false
  let disposed = false

  const fire = () => {
    const now = Date.now()
    if (now - lastFiredAt < REPEAT_GUARD_MS) return
    const top = handlers[handlers.length - 1]
    // Пустой стек при нажатии — рассинхронизация с хостом (кнопку не успели убрать).
    // Молча ничего не делаем: увести пользователя наугад хуже.
    if (!top) return
    lastFiredAt = now
    top()
  }

  const sync = () => {
    if (!supported() || disposed) return
    if (handlers.length > 0) {
      if (!subscribed) {
        adapter.onClick(fire)
        subscribed = true
      }
      adapter.show()
    } else {
      adapter.hide()
    }
  }

  return {
    isSupported: supported,

    register: (handler) => {
      if (!supported()) return () => {}
      handlers = [...handlers, handler]
      sync()
      let removed = false
      return () => {
        if (removed) return
        removed = true
        handlers = handlers.filter((item) => item !== handler)
        sync()
      }
    },

    dispose: () => {
      if (disposed) return
      disposed = true
      handlers = []
      if (!supported()) return
      if (subscribed) {
        // Отписка той же ссылкой, что и подписка, — этого требует документация MAX,
        // иначе обработчик остаётся жить в мосте и срабатывает после ухода со страницы.
        adapter.offClick(fire)
        subscribed = false
      }
      adapter.hide()
    },
  }
}
