/**
 * Жив ли мост MAX в обе стороны.
 *
 * Зачем это вообще. Почти все вызовы моста — «выстрелил и забыл»: `postEvent` ничего не
 * возвращает, поэтому `BackButton.show()` отрабатывает без ошибки и выставляет `isVisible`
 * даже тогда, когда клиент выбросил событие и стрелки не появилось. Спрашивать у моста,
 * получилось ли, бессмысленно — он отвечает про своё локальное состояние, а не про шапку.
 *
 * Клиент выбрасывает события, когда мини-приложение открыто не с того origin, что
 * зарегистрирован за ботом (см. tools/max-dev-relay — там же и лечение). Определять это по
 * `platform` нельзя: раньше здесь стояло исключение всего веба, выведенное из проверки на
 * незарегистрированном стенде, и оно заодно отключало кнопку на десктопе, где она работает.
 *
 * Поэтому проверяем не окружение, а само нужное свойство: отвечает ли клиент. `getLaunchContext`
 * — единственная группа вызовов, которая идёт через `createRequest`, то есть кладёт `requestId`
 * и ждёт ответа. Ответил — мост жив в обе стороны, кнопке можно верить. Промолчал — не верим
 * и оставляем экранам их собственную навигацию.
 *
 * Проба одна на запуск: спрашиваем в `initRuntime`, дальше все читают готовый ответ синхронно.
 * Так экраны не мигают своей кнопкой в ожидании ответа.
 */

import { getMaxWebApp } from "./detectPlatform"

/**
 * Свой срок ожидания, короче десяти секунд у SDK: это стартовый вызов, и задерживать на нём
 * запуск нельзя. Живой клиент отвечает за миллисекунды — секунды здесь means «не ответит».
 */
const PROBE_TIMEOUT_MS = 1500

let bridgeAlive = false

/**
 * Ответ пробы. До `probeMaxBridge` — `false`: пока не доказано, что клиент нас слышит,
 * занимать его шапку нельзя. Ошибиться в эту сторону значит показать лишнюю свою кнопку,
 * в обратную — оставить экран без выхода.
 */
export const isMaxBridgeAlive = (): boolean => bridgeAlive

export const probeMaxBridge = async (): Promise<boolean> => {
  // При нативном мосте спрашивать нечего: клиент инжектит `WebViewHandler` прямо в WebView,
  // SDK ходит через него, а не через postMessage, и origin там не проверяется — той беды,
  // ради которой проба написана, на этом пути просто нет. Спрашивать всё равно опасно:
  // промолчи клиент на незнакомый метод — и мы погасили бы кнопку там, где она работает.
  if (typeof (window as unknown as { WebViewHandler?: unknown }).WebViewHandler !== "undefined") {
    bridgeAlive = true
    return true
  }

  const webApp = getMaxWebApp()
  if (typeof webApp?.getLaunchContext !== "function") {
    bridgeAlive = false
    return false
  }

  try {
    const request = webApp.getLaunchContext()
    // Промах SDK по таймауту случится позже нашего и отклонит этот же промис. Гасим его
    // здесь, иначе получим unhandled rejection уже после того, как ответ никому не нужен.
    request.catch(() => {})

    bridgeAlive = await Promise.race([
      request.then(() => true),
      new Promise<boolean>((resolve) => setTimeout(() => resolve(false), PROBE_TIMEOUT_MS)),
    ])
  } catch {
    // Клиент ответил ошибкой — но ответил, значит слышит нас и канал рабочий.
    bridgeAlive = true
  }

  if (!bridgeAlive) {
    console.warn(
      "[max/bridge] Клиент не ответил на пробу: события моста уходят в пустоту. " +
        "Обычно это значит, что приложение открыто не с зарегистрированного за ботом origin."
    )
  }

  return bridgeAlive
}
